def letter_lines(lt: dict) -> list[str]:
    """The letter as numbered-line-ready text, in reading order."""
    return [lt["sender_addr"], "", *RECIPIENT, "",
            f"Datum: {lt['date']}", lt["ref"], "", lt["subject"], "",
            "Sehr geehrter Herr Mustermann,", "", *lt["body"], "",
            "Mit freundlichen Grüßen", lt["sender"]]


W, H, MARGIN = 1240, 1754, 120  # A4 at 150 dpi


def render_page(lt: dict) -> Image.Image:
    img = Image.new("RGB", (W, H), "white")
    d = ImageDraw.Draw(img)
    f, fb, fs = (ImageFont.truetype(FONT, 26), ImageFont.truetype(FONT_BOLD, 30),
                 ImageFont.truetype(FONT, 19))
    d.text((MARGIN, 90), lt["sender"], font=fb, fill=(20, 40, 90))
    d.line((MARGIN, 140, W - MARGIN, 140), fill=(20, 40, 90), width=3)
    y = 170
    for i, line in enumerate(letter_lines(lt)):
        font = fs if i == 0 else (fb if line == lt["subject"] else f)
        d.text((MARGIN, y), line, font=font, fill=(30, 30, 30))
        y += 40 if line else 22
    d.text((MARGIN, H - 90), FOOTER,
           font=fs, fill=(130, 130, 130))
    return img


def photograph(page: Image.Image, rng: random.Random) -> Image.Image:
    """Make a clean page look like a phone photo on a desk."""
    angle = rng.uniform(-3.0, 3.0)
    desk = (rng.randint(120, 160), rng.randint(100, 130), rng.randint(80, 100))
    rotated = page.rotate(angle, expand=True, fillcolor=desk, resample=Image.BICUBIC)
    canvas = Image.new("RGB", (rotated.width + 160, rotated.height + 160), desk)
    canvas.paste(rotated, (80 + rng.randint(-30, 30), 80 + rng.randint(-30, 30)))

    # Uneven lighting: darken toward one random side.
    strength = rng.uniform(0.25, 0.4)
    shade = Image.linear_gradient("L").rotate(rng.choice([0, 90, 180, 270]))
    shade = shade.resize(canvas.size).point(lambda v: 255 - int(v * strength))
    canvas = Image.composite(canvas, Image.new("RGB", canvas.size, (0, 0, 0)), shade)

    noise = Image.effect_noise(canvas.size, rng.uniform(8, 16)).convert("RGB")
    canvas = Image.blend(canvas, noise, 0.06)
    canvas = canvas.filter(ImageFilter.GaussianBlur(rng.uniform(0.4, 0.9)))
    canvas.thumbnail((1600, 1600))
    return canvas


def digital_pdf(lt: dict, path: Path) -> None:
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.pdfgen import canvas

    pdfmetrics.registerFont(TTFont("DejaVu", FONT))
    pdfmetrics.registerFont(TTFont("DejaVu-Bold", FONT_BOLD))
    c = canvas.Canvas(str(path), pagesize=A4)
    _, h = A4
    c.setFont("DejaVu-Bold", 15)
    c.drawString(57, h - 60, lt["sender"])
    y = h - 95
    for line in letter_lines(lt):
        c.setFont("DejaVu-Bold" if line == lt["subject"] else "DejaVu", 11)
        c.drawString(57, y, line)
        y -= 17 if line else 9
    c.setFont("DejaVu", 8)
    c.drawString(57, 40, FOOTER)
    c.save()


def ground_truth(lt: dict) -> dict:
    d, m, y = map(int, lt["date"].split("."))
    return {
        "id": lt["id"],
        "letter_type": lt["type"],
        "sender": lt["sender"],
        "letter_date": date(y, m, d).isoformat(),
        "amount": lt["amount"],
        "reference": lt["reference"],
        "iban": lt["iban"],
        "deadlines": lt["dl"],
        "note": lt.get("note"),
        # Everything printed on the page, in reading order: letterhead, body, footer.
        "lines": [lt["sender"], *letter_lines(lt), FOOTER],
    }


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(42)  # fixed seed: same dataset every run
    for lt in LETTERS:
        text = " ".join(letter_lines(lt))
        for dl in lt["dl"]:
            assert dl["phrase"] in text, f"{lt['id']}: phrase not in letter: {dl['phrase']}"
        page = render_page(lt)
        photograph(page, rng).save(OUT / f"{lt['id']}.jpg", quality=82)
        if lt["id"] in PDF_VARIANTS:
            digital_pdf(lt, OUT / f"{lt['id']}.digital.pdf")
            page.save(OUT / f"{lt['id']}.scanned.pdf", "PDF", resolution=150)
        (OUT / f"{lt['id']}.json").write_text(
            json.dumps(ground_truth(lt), ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(LETTERS)} letters to {OUT}")


